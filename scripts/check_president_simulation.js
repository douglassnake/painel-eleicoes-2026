#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={window:{},document:{readyState:'loading',addEventListener(){}}};
vm.createContext(context);
function read(file){vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});}
read('data.js');
read('presidential-colors.js');
read('presidential-surveys.js');
read('presidential-simulation.js');
const api=context.window.PresidentRunoffSimulation;
const polls=context.window.SecondRoundPolls.entries;
assert.equal(api.VERSION,'MC-2T v1.0');
assert.equal(api.DEFAULT_DRAWS,200000);
assert.equal(api.SEED,20261019);
assert.equal(polls.length,7);
assert.ok(!polls.some(p=>p.id.includes('palver')));
const all=api.simulate(polls,{draws:12000,commonShock95:2});
assert.equal(all.studies,4);
assert.equal(all.draws,12000);
assert.ok(Math.abs(all.centerFlavio-51.3)<1e-8);
assert.ok(Math.abs(all.centerLula-48.7)<1e-8);
assert.ok(Math.abs(all.centerDifference-2.6)<1e-8);
assert.equal(all.pollMinFlavio,50.3);
assert.equal(all.pollMaxFlavio,52);
assert.equal(all.histogram.length,24);
assert.equal(all.histogram.reduce((n,b)=>n+b.count,0),12000);
assert.ok(all.band90Flavio[0]<all.centerFlavio);
assert.ok(all.band90Flavio[1]>all.centerFlavio);
assert.ok(Math.abs(all.band90Flavio[0]+all.band90Lula[1]-100)<1e-8);
assert.ok(Math.abs(all.band90Flavio[1]+all.band90Lula[0]-100)<1e-8);
const same=api.simulate(polls,{draws:12000,commonShock95:2});
assert.deepEqual([...all.band90Flavio],[...same.band90Flavio]);
const withoutShock=api.simulate(polls,{draws:12000,commonShock95:0});
assert.ok(withoutShock.band90Flavio[1]-withoutShock.band90Flavio[0] <
  all.band90Flavio[1]-all.band90Flavio[0]);
const one=api.simulate([polls[0]],{draws:12000,commonShock95:0});
assert.equal(one.studies,1);
assert.ok(Math.abs(one.centerFlavio-polls[0].flavio)<1e-8);
assert.throws(()=>api.simulate([]));
assert.throws(()=>api.simulate(polls,{commonShock95:6}));
assert.throws(()=>api.simulate(polls,{draws:200001}));
assert.throws(()=>api.simulate([...polls,polls[0]]));
assert.throws(()=>api.simulate([{...polls[0],lula:2}]));
const source=fs.readFileSync('presidential-simulation-ui.js','utf8');
assert.ok(source.includes('window.PresidentialSimulationUI'));
assert.ok(source.includes("data-sim-poll"));
assert.ok(source.includes("min=\"0\" max=\"4\" step=\"0.5\""));
assert.ok(source.includes('200.000 cenários'));
assert.ok(source.includes('não intervalos preditivos da eleição'));
assert.ok(!source.includes('chance de vitória de Flávio') && !source.includes('chance de vitória de Lula'));
const app=fs.readFileSync('app.js','utf8');
assert.ok(app.includes('PresidentialSimulationUI?.teaser()'));
const front=fs.readFileSync('presidential-poll.js','utf8');
assert.ok(front.includes('PresidentialSimulationUI?.mount('));
const regional=fs.readFileSync('data.js','utf8');
assert.ok(regional.includes('Monte Carlo v3 (ITR)'));
console.log('OK: Monte Carlo MC-2T v1, cenários determinísticos, sensibilidade e separação do modelo regional/TSE.');
