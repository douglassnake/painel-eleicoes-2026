#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const sandbox={window:{}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('presidential-surveys.js','utf8'),sandbox);
const p=sandbox.window.SecondRoundPolls;
assert.ok(p&&typeof p.compact==='function'&&typeof p.full==='function');
const rows=p.entries;
assert.equal(rows.length,4);
assert.equal(new Set(rows.map(r=>r.id)).size,4);
assert.equal(rows.filter(r=>r.divulgacao==='2026-10-19').length,3);
assert.equal(rows.filter(r=>r.divulgacao==='2026-10-17').length,1);
const atlas=rows.find(x=>x.instituto==='AtlasIntel/Bloomberg');
const poder=rows.find(x=>x.instituto==='PoderData/AYA');
const nexus=rows.find(x=>x.instituto==='Nexus/BTG Pactual');
const verita=rows.find(x=>x.instituto==='Instituto Veritá');
assert.deepEqual([atlas.flavio,atlas.lula,atlas.amostra,atlas.margemErroPp],[51.1,48.9,4998,1]);
assert.deepEqual([poder.flavio,poder.lula,poder.amostra,poder.margemErroPp],[52,48,3000,1.8]);
assert.deepEqual([nexus.flavio,nexus.lula,nexus.amostra,nexus.margemErroPp],[50.3,49.7,2002,2]);
assert.deepEqual([verita.flavio,verita.lula,verita.amostra],[51.1,48.9,15554]);
assert.ok(rows.every(r=>r.registroInformado.startsWith('BR-')&&r.confianca===95));
assert.ok(rows.every(r=>!r.registroConferidoNoPesqEle&&r.fonteUrl.startsWith('https://')));
const short=p.compact(),full=p.full();
assert.equal((short.match(/data-survey-id=/g)||[]).length,3);
assert.equal((full.match(/data-survey-id=/g)||[]).length,4);
assert.ok(short.includes('não representam votos apurados'));
assert.ok(!short.includes('window.Runoff2026'));
console.log('OK: 3 pesquisas 19/10, Veritá 17/10, datas, metadados, fontes e séries separadas do TSE.');
